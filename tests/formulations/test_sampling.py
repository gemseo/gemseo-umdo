@pytest.mark.parametrize("doe_samples", [_THREE_SAMPLES], indirect=True)
@pytest.mark.parametrize(("statistic_name", "statistic_parameters"), _STATISTICS)
def test_iterative_statistic_after_interrupted_sampling(
    create_umdo_formulation,
    statistic_name,
    statistic_parameters,
    monkeypatch,
):
    """Check that an interrupted sampling does not alter the next estimations.

    The sampling at a first input point raises an error once all the samples
    are evaluated.
    The statistic and its Jacobian at a second input point
    are the same as those estimated in one go.
    """
    formulation = create_umdo_formulation(True)
    function = formulation.create_objective("f", statistic_name, **statistic_parameters)
    compute_samples = formulation.compute_samples

    def _interrupt(*args, **kwargs):
        compute_samples(*args, **kwargs)
        msg = "Interruption."
        raise RuntimeError(msg)

    monkeypatch.setattr(formulation, "compute_samples", _interrupt)
    with pytest.raises(RuntimeError, match=r"^Interruption\.$"):
        function.evaluate(array([0.0] * 3))
    with pytest.raises(RuntimeError, match=r"^Interruption\.$"):
        function.jac(array([0.0] * 3))

    monkeypatch.setattr(formulation, "compute_samples", compute_samples)
    reference_function = create_umdo_formulation(False).create_objective(
        "f", statistic_name, **statistic_parameters
    )
    input_value = array([0.5, 0.2, 0.1])
    assert_almost_equal(
        function.evaluate(input_value), reference_function.evaluate(input_value)
    )
    assert_almost_equal(function.jac(input_value), reference_function.jac(input_value))


@pytest.mark.parametrize("doe_samples", [_THREE_SAMPLES], indirect=True)
@pytest.mark.parametrize(("statistic_name", "statistic_parameters"), _STATISTICS)
def test_iterative_statistic_after_failed_sampling(
    create_umdo_formulation,
    disciplines,
    statistic_name,
    statistic_parameters,
    monkeypatch,
):
    """Check that a sampling failing in the DOE does not alter the next estimations.

    The evaluation of a discipline raises an error that the DOE algorithm
    does not catch, at the second sample of a first input point.
    The callbacks of the DOE algorithm are restored
    and the statistic and its Jacobian at a second input point
    are the same as those estimated in one go.
    """
    formulation = create_umdo_formulation(True)
    function = formulation.create_objective("f", statistic_name, **statistic_parameters)
    doe_algo_settings = formulation._settings.doe_algo_settings
    original_callbacks = doe_algo_settings.callbacks
    discipline = disciplines[0]
    run = discipline._run

    def _fail(*args, **kwargs):
        if discipline.io.data["u"][0] == 1.0:
            msg = "Failure."
            raise RuntimeError(msg)
        return run(*args, **kwargs)

    monkeypatch.setattr(discipline, "_run", _fail)
    with pytest.raises(RuntimeError, match=r"^Failure\.$"):
        function.evaluate(array([0.0] * 3))
    assert doe_algo_settings.callbacks == original_callbacks
    with pytest.raises(RuntimeError, match=r"^Failure\.$"):
        function.jac(array([0.0] * 3))
    assert doe_algo_settings.callbacks == original_callbacks

    monkeypatch.undo()
    reference_function = create_umdo_formulation(False).create_objective(
        "f", statistic_name, **statistic_parameters
    )
    input_value = array([0.5, 0.2, 0.1])
    assert_almost_equal(
        function.evaluate(input_value), reference_function.evaluate(input_value)
    )
    assert_almost_equal(function.jac(input_value), reference_function.jac(input_value))


