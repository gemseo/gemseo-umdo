def _make_discipline_fail(
    monkeypatch: pytest.MonkeyPatch,
    discipline: Discipline,
    method_name: str,
    u_values: Collection[float] | None = None,
) -> None:
    """Make a method of a discipline fail at some samples.

    Args:
        monkeypatch: The pytest fixture to patch the discipline.
        discipline: The discipline.
        method_name: The name of the method, e.g. `"_compute_jacobian"`.
        u_values: The values of `u` at which the method fails.
            If `None`, it fails at all the samples.
    """
    method = getattr(discipline, method_name)

    def _fail(*args, **kwargs):
        if u_values is None or discipline.io.data["u"][0] in u_values:
            msg = f"Failure of {method_name}."
            raise ValueError(msg)
        return method(*args, **kwargs)

    monkeypatch.setattr(discipline, method_name, _fail)


def _make_function_fail(
    monkeypatch: pytest.MonkeyPatch,
    formulation: Sampling,
    function_name: str,
    method_name: str = "jac",
) -> None:
    """Make a method of a function of the sampling problem fail at all the samples.

    Args:
        monkeypatch: The pytest fixture to patch the function.
        formulation: The U-MDO formulation.
        function_name: The name of the function.
        method_name: The name of the method, e.g. `"jac"`.
    """
    (function,) = (
        function
        for function in formulation.mdo_formulation.problem.functions
        if function.name == function_name
    )

    def _fail(*args, **kwargs):
        msg = f"Failure of {method_name} of {function_name}."
        raise ValueError(msg)

    monkeypatch.setattr(function, method_name, _fail)


