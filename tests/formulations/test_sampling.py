def test_statistic_jacobian_with_too_few_samples(
    umdo_formulation,
    disciplines,
    statistic_name,
    statistic_parameters,
    failing_method_name,
    monkeypatch,
    snapshot,
):
    """Check the error raised when the Jacobian of a statistic lacks samples.

    The evaluation of the output or of its gradient fails at one of the two samples,
    while these statistics require at least two samples.
    The error points to the output and its gradient.

    When only the gradient fails,
    the statistic is estimated from the two samples before its Jacobian,
    as an optimizer does and as the iterative estimation requires.
    """
    _make_discipline_fail(monkeypatch, disciplines[0], failing_method_name, (1.0,))
